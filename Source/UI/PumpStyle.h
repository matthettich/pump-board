inline juce::Colour hex (juce::uint32 rgb, float a = 1.0f)
{
    return juce::Colour::fromFloatRGBA ((float) ((rgb >> 16) & 0xff) / 255.0f,
                                        (float) ((rgb >> 8) & 0xff) / 255.0f,
                                        (float) (rgb & 0xff) / 255.0f,
                                        a);
}

inline juce::Colour mix (juce::Colour a, juce::Colour b, float t)   // t = amount of b
{
    return juce::Colour::fromFloatRGBA (a.getFloatRed()   + (b.getFloatRed()   - a.getFloatRed())   * t,
                                        a.getFloatGreen() + (b.getFloatGreen() - a.getFloatGreen()) * t,
                                        a.getFloatBlue()  + (b.getFloatBlue()  - a.getFloatBlue())  * t,
                                        a.getFloatAlpha() + (b.getFloatAlpha() - a.getFloatAlpha()) * t);
}

inline juce::Colour withAlpha (juce::Colour c, float a) { return c.withAlpha (a); }

// JUCE's String(const char*) asserts on anything above ASCII: UTF-8 literals must say so.
inline juce::String u8 (const char* s) { return juce::String (juce::CharPointer_UTF8 (s)); }

// OKLCH -> sRGB, as pump builds its rainbow tints: equal lightness reads at equal strength whatever the hue.
inline juce::Colour oklch (float L, float C, float hueDeg, float alpha = 1.0f)
{
    const double h = (double) hueDeg * 3.14159265358979323846 / 180.0;
    const double a = C * std::cos (h), b = C * std::sin (h);
    const double l_ = L + 0.3963377774 * a + 0.2158037573 * b;
    const double m_ = L - 0.1055613458 * a - 0.0638541728 * b;
    const double s_ = L - 0.0894841775 * a - 1.2914855480 * b;
    const double l = l_ * l_ * l_, m = m_ * m_ * m_, s3 = s_ * s_ * s_;
    double rgb[3] = {  4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s3,
                      -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s3,
                      -0.0041960863 * l - 0.7034186147 * m + 1.7076147010 * s3 };
    for (double& c : rgb)
    {
        c = juce::jlimit (0.0, 1.0, c);
        c = c <= 0.0031308 ? 12.92 * c : 1.055 * std::pow (c, 1.0 / 2.4) - 0.055;
    }
    return juce::Colour::fromFloatRGBA ((float) rgb[0], (float) rgb[1], (float) rgb[2], alpha);
}

