// ---- the skin the whole app draws in ----------------------------------------------------------------
// One flag, read wherever a panel builds its theme. Panels build their palette in their constructor, so
// flipping it is not enough on its own: the window rebuilds its content (see MainWindow) and every panel
// then reads the new value. Default dark, which is what the board has always been.
inline bool& darkMode() { static bool dark = true; return dark; }
inline bool isDark() { return darkMode(); }
inline void setDark (bool dark) { darkMode() = dark; }

// The neon a pedal wears on the board, by category. Shared by the painted prototype and the real slot views.
inline juce::Colour accentForCategory (const juce::String& category)
{
    if (category == "DRIVE")    return accents::tube().neon;
    if (category == "TIME")     return accents::echo().neon;
    if (category == "SPACE")    return accents::spring().neon;
    if (category == "FILTER")   return accents::eq().neon;
    if (category == "DYNAMICS") return accents::comp().neon;
    if (category == "MOD")      return accents::swirl().neon;
    return accents::machine().neon;
}

// pump's Theme: every surface derived from one accent (pump's own maths, both variants).
struct Theme
{
    bool dark = true;
    juce::Colour bg, panel, panel2, ink, ink2, dim, neon, neonInk, on, second, red, grid, screen, glow;

    void build (const Accent& a, bool darkMode)
    {
        dark = darkMode;
        const juce::Colour white = hex (0xFFFFFF), black = hex (0x07070B);

        if (! dark)
        {
            bg      = mix (white, a.neon, 0.16f);
            panel   = mix (white, a.neon, 0.08f);
            panel2  = mix (white, a.neon, 0.30f);
            ink     = a.deep;
            ink2    = mix (a.deep, bg, 0.38f);
            dim     = mix (mix (a.neon, a.deep, 0.30f), white, 0.42f);
            neon    = a.neon;
            neonInk = a.deep;
            on      = mix (white, a.neon, 0.06f);
            second  = mix (a.second, black, 0.08f);
            red     = hex (0xD0302A);
            grid    = withAlpha (a.deep, 0.11f);
            screen  = mix (white, a.neon, 0.05f);
            glow    = withAlpha (a.neon, 0.0f);
        }
        else
        {
            bg      = mix (black, a.neon, 0.07f);
            panel   = mix (black, a.neon, 0.10f);
            panel2  = mix (black, a.neon, 0.19f);
            ink     = mix (a.neon, white, 0.18f);
            ink2    = mix (a.neon, bg, 0.38f);
            dim     = mix (a.neon, bg, 0.70f);
            neon    = a.neon;
            neonInk = mix (black, a.neon, 0.05f);
            on      = mix (black, a.neon, 0.05f);
            second  = mix (a.second, white, 0.15f);
            red     = hex (0xFF5A4E);
            grid    = withAlpha (a.neon, 0.10f);
            screen  = mix (black, a.neon, 0.04f);
            glow    = withAlpha (a.neon, 0.22f);
        }
    }
};

// ---- fonts ----------------------------------------------------------------------------------------------------
// Share Tech Mono for labels, JetBrains Mono for numbers. pump embeds these (SIL OFL 1.1) in FontData.cpp, and so
// does this port now: the TTFs are compiled into the app by juce_add_binary_data (CMake target PumpBoardFonts), with
// the licence texts copied into the bundle's Resources. The file lookup below is only a fallback, so a build without
// the binary-data target still draws text.
namespace fonts
{
    // The embedded copy. A null pair means the binary-data target is not linked in, and the fallback below runs.
    struct Embedded { const char* data; int size; };

    inline Embedded embeddedFont (const juce::String& fileName)
    {
        if (fileName.startsWith ("ShareTechMono"))
            return { pumpfonts::ShareTechMonoRegular_ttf, pumpfonts::ShareTechMonoRegular_ttfSize };

        if (fileName.startsWith ("JetBrainsMono-Regular"))
            return { pumpfonts::JetBrainsMonoRegular_ttf, pumpfonts::JetBrainsMonoRegular_ttfSize };

        if (fileName.startsWith ("JetBrainsMono-Bold"))
            return { pumpfonts::JetBrainsMonoBold_ttf, pumpfonts::JetBrainsMonoBold_ttfSize };

        return {};
    }

    inline juce::Typeface::Ptr load (const juce::String& fileName)
    {
        if (const auto e = embeddedFont (fileName); e.data != nullptr && e.size > 0)
            if (auto tf = juce::Typeface::createSystemTypefaceFor (e.data, (size_t) e.size))
                return tf;

        juce::Array<juce::File> candidates;
        auto dir = juce::File::getCurrentWorkingDirectory();

        for (int i = 0; i < 7; ++i)
        {
            candidates.add (dir.getChildFile ("external/pump/common/fonts").getChildFile (fileName));
            dir = dir.getParentDirectory();
        }

        for (auto& f : candidates)
        {
            if (! f.existsAsFile())
                continue;

            juce::MemoryBlock mb;
            if (! f.loadFileAsData (mb))
                continue;

            if (auto tf = juce::Typeface::createSystemTypefaceFor (mb.getData(), mb.getSize()))
                return tf;
        }

        return {};
    }

    inline juce::Typeface::Ptr& labelTypeface() { static juce::Typeface::Ptr p = load ("ShareTechMono-Regular.ttf"); return p; }
    inline juce::Typeface::Ptr& monoTypeface()  { static juce::Typeface::Ptr p = load ("JetBrainsMono-Regular.ttf"); return p; }

    // Label (Share Tech Mono) or mono (JetBrains Mono). `tracking` is in pixels, as pump's
    // textLetterSpacing is; JUCE's extra kerning is a proportion of the font height, so divide.
    inline juce::Font get (bool label, float height, float tracking = 0.0f)
    {
        auto& tf = label ? labelTypeface() : monoTypeface();

        juce::Font f = tf != nullptr ? juce::Font (juce::FontOptions (tf).withHeight (height))
                                     : juce::Font (juce::FontOptions (juce::Font::getDefaultMonospacedFontName(),
                                                                      height, juce::Font::plain));

        return tracking != 0.0f ? f.withExtraKerningFactor (tracking / juce::jmax (1.0f, height)) : f;
    }
}

// ---- drawing primitives (the Simple skin) ---------------------------------------------------------------------
namespace draw
{
    // A Simple-skin key/screen: fill, 1.5 px ink outline, and an offset outlined block behind it.
    inline void keyBox (juce::Graphics& g, const Theme& t, juce::Rectangle<float> r,
                        bool filled, bool pressed = false, juce::Colour fillOverride = juce::Colour(), float offset = 4.0f)
    {
        const float o = pressed ? 1.0f : offset;

        if (o > 0.0f)
        {
            g.setColour (t.bg);
            g.fillRect (r.translated (o, o));
            g.setColour (t.dim);
            g.drawRect (r.translated (o, o).reduced (0.75f), 1.5f);
        }

        g.setColour (fillOverride.isTransparent() ? (filled ? t.ink : t.bg) : fillOverride);
        g.fillRect (r);
        g.setColour (t.ink);
        g.drawRect (r.reduced (0.75f), 1.5f);
    }

    // A screen area (graphs, readouts): panel fill, ink outline, offset block.
    inline void screenBox (juce::Graphics& g, const Theme& t, juce::Rectangle<float> r)
    {
        g.setColour (t.bg);
        g.fillRect (r.translated (5.0f, 5.0f));
        g.setColour (t.dim);
        g.drawRect (r.translated (5.0f, 5.0f).reduced (0.75f), 1.5f);
        g.setColour (t.screen);
        g.fillRect (r);
        g.setColour (t.ink);
        g.drawRect (r.reduced (0.75f), 1.5f);
    }

    inline void text (juce::Graphics& g, const juce::String& s, juce::Rectangle<float> area,
                      juce::Colour c, float size, juce::Justification just = juce::Justification::centredLeft,
                      bool label = true, float tracking = 0.8f)
    {
        g.setFont (fonts::get (label, size, tracking));
        g.setColour (c);
        g.drawText (s, area, just, false);
    }

    // Section caption, small caps with tracking.
    inline void caption (juce::Graphics& g, const Theme& t, juce::Point<float> at, const juce::String& s,
                         juce::Colour c = juce::Colour())
    {
        text (g, s.toUpperCase(), { at.x, at.y, 400.0f, 14.0f },
              c.isTransparent() ? t.ink2 : c, 11.0f, juce::Justification::centredLeft, true, 1.2f);
    }

    // pump's Dial::draw: 270 degree arc (0.75pi .. 2.25pi in pump's angle convention), flat disc, ink pointer.
    // pump's angles start at 3 o'clock and run clockwise; JUCE's addCentredArc starts at 12 o'clock.
    inline void arc (juce::Graphics& g, juce::Point<float> centre, float rad,
                     float fromPump, float toPump, float thickness, juce::Colour c)
    {
        if (std::abs (toPump - fromPump) < 0.01f)
            return;

        juce::Path p;
        p.addCentredArc (centre.x, centre.y, rad, rad, 0.0f,
                         fromPump - juce::MathConstants<float>::halfPi,
                         toPump  - juce::MathConstants<float>::halfPi,
                         true);
        g.setColour (c);
        g.strokePath (p, juce::PathStrokeType (thickness, juce::PathStrokeType::curved, juce::PathStrokeType::butt));
    }

    inline void dial (juce::Graphics& g, const Theme& t, juce::Rectangle<float> r,
                      const juce::String& label, float norm, const juce::String& valueText,
                      float rad = 20.0f, bool bipolar = false, bool enabled = true)
    {
        const float a0 = juce::MathConstants<float>::pi * 0.75f;
        const float a1 = juce::MathConstants<float>::pi * 2.25f;
        const juce::Point<float> c { r.getCentreX(), r.getY() + 16.0f + rad + 2.0f };

        text (g, label, { r.getX(), r.getY() + 1.0f, r.getWidth(), 14.0f },
              enabled ? t.ink2 : t.dim, rad < 18.0f ? 10.5f : 11.5f, juce::Justification::centred, true, 1.0f);

        arc (g, c, rad, a0, a1, rad < 18.0f ? 4.0f : 5.0f, t.dim);                       // track

        const float from = bipolar ? juce::MathConstants<float>::pi * 1.5f : a0;
        const float to   = a0 + (a1 - a0) * juce::jlimit (0.0f, 1.0f, norm);
        arc (g, c, rad, juce::jmin (from, to), juce::jmax (from, to),
             rad < 18.0f ? 4.0f : 5.0f, enabled ? t.neon : t.dim);                       // value

        g.setColour (t.bg);
        g.fillEllipse (c.x - (rad - 5.0f), c.y - (rad - 5.0f), (rad - 5.0f) * 2.0f, (rad - 5.0f) * 2.0f);
        g.setColour (enabled ? t.ink : t.dim);
        g.drawEllipse (c.x - (rad - 5.0f), c.y - (rad - 5.0f), (rad - 5.0f) * 2.0f, (rad - 5.0f) * 2.0f, 1.5f);

        const juce::Point<float> dir { std::cos (to), std::sin (to) };
        g.setColour (enabled ? t.ink : t.dim);
        g.drawLine (juce::Line<float> (c.x + dir.x * (rad - 14.0f) * 0.25f,
                                       c.y + dir.y * (rad - 14.0f) * 0.25f,
                                       c.x + dir.x * (rad - 6.5f),
                                       c.y + dir.y * (rad - 6.5f)), 2.2f);

        text (g, valueText, { r.getX(), c.y + rad + 5.0f, r.getWidth(), 16.0f },
              enabled ? t.ink : t.dim, rad < 18.0f ? 10.0f : 11.0f, juce::Justification::centred, false);
    }
}
